#pragma once

#include <stdint.h>

// ============================================================================
// ESPBridge — конфигурация железа и сети
//
// Плата WT32-ETH01. Почти все GPIO заняты интерфейсом RMII к LAN8720A,
// поэтому распиновка портов данных выбрана из того немногого, что выведено
// наружу и при этом двунаправленно.
// ============================================================================

// --- Ethernet / LAN8720A ----------------------------------------------------
// Значения продиктованы разводкой платы, менять нельзя.
//
// Тактирование 50 МГц приходит на GPIO0 от внешнего осциллятора — по этой
// причине GPIO0 недоступен как обычный пин, а вход в режим прошивки требует
// ручного замыкания на GND.
//
// MDC/MDIO и режим тактирования совпадают со значениями ETH_ESP32_EMAC_DEFAULT_CONFIG()
// для ESP32, но заданы здесь явно: полагаться на умолчания фреймворка в том,
// что определяется разводкой конкретной платы, — источник трудноуловимых
// поломок при обновлении IDF.
#define ETH_MDC_GPIO            23
#define ETH_MDIO_GPIO           18
#define ETH_PHY_RST_GPIO        -1   // аппаратного сброса PHY на плате нет
#define ETH_PHY_ADDR            1
#define ETH_PHY_POWER_GPIO      16   // питание PHY, поднимается до инициализации

// --- Порты данных -----------------------------------------------------------
// UART1 — CRSF. Пины 32/33 без strapping-функций и без участия в загрузке,
// то есть самые «чистые» из доступных. CRSF чувствителен к таймингу, поэтому
// лучшие пины отданы именно ему.
#define PORT0_UART_NUM          UART_NUM_1
#define PORT0_TX_GPIO           32
#define PORT0_RX_GPIO           33

// UART2 — MAVLink. Пин 15 при старте подтянут и влияет на вывод boot-лога;
// для MAVLink это безразлично, для CRSF было бы риском.
#define PORT1_UART_NUM          UART_NUM_2
#define PORT1_TX_GPIO           14
#define PORT1_RX_GPIO           15

// UART0 (TXD0/RXD0) сознательно не используется под данные — это порт
// прошивки и отладочного лога.

// GPIO2 выведен наружу и свободен — индикация состояния.
#define STATUS_LED_GPIO         2

// --- Сеть -------------------------------------------------------------------
// Прямое соединение двух модулей кабелем: DHCP-сервера в такой топологии нет,
// адреса статические. Роль задаётся флагом сборки в platformio.ini.

#if defined(BRIDGE_ROLE_GROUND)
  #define BRIDGE_ROLE_NAME      "GROUND"
  #define BRIDGE_LOCAL_IP       "192.168.4.1"
  #define BRIDGE_PEER_IP        "192.168.4.2"
#elif defined(BRIDGE_ROLE_AIR)
  #define BRIDGE_ROLE_NAME      "AIR"
  #define BRIDGE_LOCAL_IP       "192.168.4.2"
  #define BRIDGE_PEER_IP        "192.168.4.1"
#else
  #error "Не задана роль модуля. Собирайте окружение 'ground' или 'air'."
#endif

#define BRIDGE_NETMASK          "255.255.255.0"
// Шлюза в прямом соединении нет. Указываем собственный адрес, чтобы стек
// не пытался маршрутизировать наружу.
#define BRIDGE_GATEWAY          BRIDGE_LOCAL_IP

// UDP-порты: каждый порт данных получает свой, чтобы потоки CRSF и MAVLink
// не смешивались и могли иметь разную политику доставки.
#define PORT0_UDP_PORT          14551
#define PORT1_UDP_PORT          14552

#define BRIDGE_HOSTNAME         "espbridge-" BRIDGE_ROLE_NAME

// Пароль прошивки по сети. Должен совпадать с --auth в platformio.ini.
// Без него любой в сети может залить в модуль свою прошивку.
#ifndef OTA_PASSWORD
  #define OTA_PASSWORD          "espbridge"
#endif

// --- Буферы и тайминги ------------------------------------------------------

// Приёмный буфер драйвера UART. Должен вмещать поток за время между опросами
// с запасом: на 400 кбод это 40 байт на миллисекунду.
#define UART_RX_BUFFER_SIZE     2048
#define UART_TX_BUFFER_SIZE     2048

// Максимальный размер UDP-датаграммы. CRSF-фрейм максимум 64 байта,
// MAVLink v2 — 280, с запасом на агрегацию нескольких фреймов.
#define UDP_PACKET_MAX          512

// Сколько ждать попутчиков перед отправкой накопленного в сеть.
// Компромисс: меньше — больше мелких датаграмм и накладных расходов
// на заголовки; больше — выше задержка. При 500 мкс на 400 кбод в пакет
// собирается около 20 байт, примерно один CRSF-фрейм.
#define TX_AGGREGATE_US         500

// Партнёр считается живым, если данные приходили не позже этого срока.
#define PEER_TIMEOUT_MS         1000
